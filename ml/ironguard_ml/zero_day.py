"""Zero-day LOFO experiment (MODEL_SPEC §6.3) → eval_summary.json `zero_day`.

1. Train base PreyNet seeds 0/1/2 WITHOUT job_task (`exclude_held_out`); θ = VAL 1%-FPR threshold.
2. EWR on the held-out job_task test conversations (base only).
3. Train a chloroplast from synthetic positives that never include those test conversations.
4. Re-measure with the chloroplast (flag = base risk >= θ OR chloroplast fired, as in `infer`,
   where a fired chloroplast locks), and check base families' TEST FPR / hard-negative FPR.
5. Sample efficiency: N synthetic positives → EWR@3.

Synthetic positives come from `data/generated/zd_job_task/` (Algae output for a one-sentence
alert) when it exists. Otherwise a clearly labelled proxy: half of the v1 job_task conversations
train the chloroplast and the other half are the test set. The proxy shares a generator and prompt
with its test half, so it is optimistic and marked `available: false`.
"""

import json
from collections.abc import Sequence
from pathlib import Path

import numpy as np

from ironguard_ml.chloroplast import MIN_CONVERSATIONS, Base, build_negative_bank, train
from ironguard_ml.data import DATA_DIR, HELD_OUT_DEFAULT, Conversation, exclude_held_out
from ironguard_ml.features import CACHE_DIR, turn_vectors
from ironguard_ml.infer import apply_chloroplast
from ironguard_ml.metrics import summarize, threshold_at_fpr
from ironguard_ml.train import (
    SEEDS,
    calibrated_val_rows,
    encode,
    fit,
    predict,
    risks,
    scored,
    temperatures,
)

FAMILY = HELD_OUT_DEFAULT  # "job_task"
ZD_FAMILY = f"zd_{FAMILY}"
ZD_DIR = DATA_DIR / "generated" / ZD_FAMILY
ALERT = ("Texts offer an easy remote job, then ask you to pay a deposit to unlock "
         "higher-paying tasks.")
LABEL = "Pay-to-unlock job tasks"
SAMPLE_SIZES = (25, 50, 100, 200)
K = 3
MAX_NEG = 120  # proxy hard negatives (the /v1/zero-day default n_neg)
NOTES = (
    ("Base PreyNet is re-trained without job_task (seeds 0/1/2); θ = its VAL 1%-FPR threshold. "
     "Metrics are means over seeds."),
    ("With the chloroplast a prefix is flagged when base risk >= θ OR the chloroplast fires "
     "(p >= its threshold), matching infer.py where a fired chloroplast locks."),
    ("Chloroplast negatives: the synthetic hard negatives + 1,000 benign and 500 other-family "
     "prefixes from the LOFO base TRAIN split; threshold = 1% FPR on a held-out 20% of those "
     "negative conversations. No TEST data trains or tunes it."),
    "regression_test: TEST split without job_task (base families + benign).",
    "sample_efficiency: null where fewer synthetic positives exist than N.",
    "time_to_protection_s = generate_seconds + train_seconds (null if generation time is unknown).",
)
PROXY_NOTE = ("source v1_proxy: half of v1 job_task trains the chloroplast and the other half is "
              "the test set. Same generator and prompt as the test set, so it overstates zero-day "
              "performance. Not pitch evidence (available: false).")
ALGAE_NOTE = "source algae: positives generated by Algae from the one-sentence alert."


def read_records(directory: Path) -> list[dict]:
    """Raw conversation dicts of every *.jsonl in a directory (validated later by train())."""
    return [json.loads(line) for path in sorted(directory.glob("*.jsonl"))
            for line in path.read_text(encoding="utf-8").splitlines() if line.strip()]


def synthetic_data(splits: dict, v1_records: dict[str, dict], zd_dir: Path = ZD_DIR) -> dict:
    """Positives / negatives for the chloroplast and the job_task test set they never touch."""
    pool = sorted(exclude_held_out(splits, FAMILY)["held_out"], key=lambda c: c.id)
    zd = read_records(zd_dir) if zd_dir.is_dir() else []
    if zd:
        meta_path = zd_dir / "meta.json"
        meta = json.loads(meta_path.read_text()) if meta_path.exists() else {}
        return {"source": "algae", "test": tuple(pool),
                "pos": [r for r in zd if r["family"] == ZD_FAMILY],
                "neg": [r for r in zd if r["family"] == "benign"],
                "alert": meta.get("alert", ALERT), "generate_seconds": meta.get("generate_seconds")}
    order = np.random.default_rng(0).permutation(len(pool))
    half = len(pool) // 2
    hard_negatives = sorted((c for c in splits["train"] if c.hard_negative), key=lambda c: c.id)
    return {"source": "v1_proxy", "test": tuple(pool[i] for i in order[half:]),
            "pos": [{**v1_records[pool[i].id], "family": ZD_FAMILY} for i in order[:half]],
            "neg": [v1_records[c.id] for c in hard_negatives[:MAX_NEG]],
            "alert": ALERT, "generate_seconds": None}


def _summary(convs: Sequence[Conversation], risk: np.ndarray, theta: float, fired=None) -> dict:
    """Metrics where a prefix is flagged iff base risk >= θ or the chloroplast fired."""
    fired = np.zeros(len(risk), bool) if fired is None else fired
    if theta > 1:  # base abstains at the cap; only the chloroplast can flag
        return summarize(scored(convs, np.where(fired, 1.0, 0.0)), 1.0)
    return summarize(scored(convs, np.where(fired, 1.0, risk)), theta)


def _seed_run(splits, data, seed, vectors, cache_dir, encoder) -> dict:
    base_splits = exclude_held_out(splits, FAMILY)
    enc = {name: encode(base_splits[name], vectors) for name in ("train", "val")}
    net = fit(enc["train"], enc["val"], seed).net
    temp = temperatures(net, enc["val"])["family"]
    theta = threshold_at_fpr(calibrated_val_rows(net, enc["val"], temp))
    base = Base(net, *build_negative_bank(net, base_splits["train"], encoder, cache_dir, seed),
                encoder=encoder, cache_dir=cache_dir)
    others = tuple(c for c in splits["test"] if c.family != FAMILY)  # base families + benign
    out_zd, out_test = predict(net, encode(data["test"], vectors)), predict(net, encode(others, vectors))
    risk_zd, risk_test = risks(out_zd["family_logits"], temp), risks(out_test["family_logits"], temp)

    def fired(manifest, out):
        return (apply_chloroplast(manifest, out["features"]) >= manifest["threshold"]).numpy()

    def chloroplast(pos):
        return train(pos, data["neg"], ZD_FAMILY, LABEL, data["alert"], base=base, seed=seed)

    manifest = chloroplast(data["pos"])
    rng = np.random.default_rng(seed)
    curve = []
    for n in SAMPLE_SIZES:
        if n > len(data["pos"]):
            curve.append(None)
            continue
        picked = [data["pos"][i] for i in sorted(rng.choice(len(data["pos"]), n, replace=False))]
        m = chloroplast(picked)
        curve.append(_summary(data["test"], risk_zd, theta, fired(m, out_zd))["ewr_at_k"][K - 1])
    return {
        "seed": seed, "theta": theta, "chloroplast_threshold": manifest["threshold"],
        "train_seconds": manifest["metrics"]["train_seconds"],
        "val_recall_at_1fpr": manifest["metrics"]["val_recall_at_1fpr"],
        "base": _summary(data["test"], risk_zd, theta),
        "chloroplast": _summary(data["test"], risk_zd, theta, fired(manifest, out_zd)),
        "test_base": _summary(others, risk_test, theta),
        "test_chloroplast": _summary(others, risk_test, theta, fired(manifest, out_test)),
        "curve": curve,
    }


def _mean(values):
    return None if any(v is None for v in values) else float(np.mean(values))


def _mean_summary(runs: list[dict], key: str) -> dict:
    return {"ewr_at_k": [_mean([r[key]["ewr_at_k"][i] for r in runs]) for i in range(6)],
            **{m: _mean([r[key][m] for r in runs])
               for m in ("lead_time", "strike_recall", "fpr", "hard_neg_fpr")}}


def run_lofo(splits: dict, v1_records: dict[str, dict], encoder=None, zd_dir: Path = ZD_DIR):
    """The `zero_day` block, or None when there are too few job_task conversations."""
    data = synthetic_data(splits, v1_records, zd_dir)
    if min(len(data["pos"]), len(data["test"])) < MIN_CONVERSATIONS:
        print(f"zero_day skipped: {len(data['pos'])} synthetic positives, "
              f"{len(data['test'])} {FAMILY} test conversations")
        return None
    cache_dir = CACHE_DIR if encoder is None else None  # never cache a test encoder's vectors

    def vectors(turns):
        return turn_vectors(turns, encoder, cache_dir)

    runs = [_seed_run(splits, data, seed, vectors, cache_dir, encoder) for seed in SEEDS]
    base, cp = _mean_summary(runs, "base"), _mean_summary(runs, "chloroplast")
    train_s = float(np.mean([r["train_seconds"] for r in runs]))
    gen_s = data["generate_seconds"]
    available = data["source"] == "algae"
    return {
        "available": available, **({} if available else {"display": "--"}),
        "family": FAMILY, "chloroplast_family_id": ZD_FAMILY, "source": data["source"],
        "alert": data["alert"], "k": K,
        "base_ewr_at_3": base["ewr_at_k"][K - 1], "chloroplast_ewr_at_3": cp["ewr_at_k"][K - 1],
        "base": base, "chloroplast": cp,
        "regression_test": {"base": _mean_summary(runs, "test_base"),
                            "with_chloroplast": _mean_summary(runs, "test_chloroplast")},
        "sample_efficiency": [{"n": n, "ewr_at_3": _mean([r["curve"][i] for r in runs])}
                              for i, n in enumerate(SAMPLE_SIZES)],
        "train_seconds": round(train_s, 3),
        "generate_seconds": gen_s,
        "time_to_protection_s": None if gen_s is None else round(gen_s + train_s, 3),
        "n_synthetic_pos": len(data["pos"]), "n_synthetic_neg": len(data["neg"]),
        "n_test": len(data["test"]),
        "seeds": [{k: r[k] for k in ("seed", "theta", "chloroplast_threshold", "train_seconds",
                                     "val_recall_at_1fpr")} for r in runs],
        "notes": [*NOTES, ALGAE_NOTE if available else PROXY_NOTE],
    }
